window.optionPlain = function (label) {
  var book = window.OPTION_WORDS || {};
  var text = String(label || "").replace(/\s+/g, " ").trim();
  if (book[text]) return book[text];
  var best = "";
  var hit = "";
  Object.keys(book).forEach(function (key) {
    if (key.length < 3) return;
    if (text.indexOf(key) !== -1 && key.length > best.length) {
      best = key;
      hit = book[key];
    }
  });
  if (hit) return hit;
  if (/스티어링 휠/.test(text)) return "핸들을 감싼 소재와 모양입니다.";
  if (/휠|스포크/.test(text) && /인치|알로이|단조/.test(text)) return "출고될 때 달려 있는 바퀴입니다. 인치가 크면 모습이 달라지고, 승차감이 조금 단단해질 수 있습니다.";
  if (/우드|오픈\s*-?\s*포어|월넛|라임|애쉬|메이플|버치|벌치/.test(text) && /트림|우드/.test(text)) return "대시보드와 문에 들어간 나무 장식입니다. 나무 종류와 무늬가 다릅니다.";
  if (/시트 벨트/.test(text)) return "안전벨트 색이 실내와 맞춰져 있습니다.";
  if (/아티코|나파|마이크로컷|마이크로파이버|가죽/.test(text)) return "시트를 감싼 가죽 또는 인조 가죽입니다. 재질과 색이 다릅니다.";
  return "";
};
