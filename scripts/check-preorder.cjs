const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),html=fs.readFileSync(path.join(root,'preorder.html'),'utf8');
const categories=['MY27 GLE','MY27 GLS','V클래스','전기차 통합'];
const cards=html.match(/<section[^>]*aria-label="사전예약 차종"[^>]*>([\s\S]*?)<\/section>/)[1];
assert.deepEqual([...cards.matchAll(/data-preorder-category="([^"]+)"/g)].map(x=>x[1]),categories);
assert.equal([...cards.matchAll(/<article\b/g)].length,4);
assert.doesNotMatch(html,/id="sclass"|value="S클래스"|S-Class 사전예약/i);
assert.deepEqual([...html.matchAll(/name="carModel" value="([^"]+)"/g)].map(x=>x[1]),['신형 GLE','신형 GLS','V클래스','전기차 통합']);
assert.match(html,/id="ev-model" name="evModel"/);
assert.match(html,/name="evModel"[^>]*>[\s\S]*?GLB 일렉트릭[\s\S]*?GLC 일렉트릭[\s\S]*?CLA 일렉트릭/);
for(const file of ['gle-my27.html','gls-my27.html','s-class.html']) assert.ok(fs.existsSync(path.join(root,file)),file+' missing');
const ctx={window:{},document:{readyState:'loading',addEventListener(){}}};vm.createContext(ctx);vm.runInContext(fs.readFileSync(path.join(root,'glb-details.js'),'utf8'),ctx);
const detail=ctx.window.BenzGLBDetails;
assert.ok(detail.optionCount>=25);
assert.equal(detail.comparisonRows.length,10);
const out=detail.render();assert.match(out,/국내 GLB 일렉트릭은 5인승/);assert.match(out,/추후 업데이트 예정/);assert.match(out,/국내 MCT/);assert.match(out,/WLTP 최대 631km/);assert.match(out,/미기재/);
assert.ok(!/undefined|NaN/.test(out));assert.doesNotMatch(out,/사양 근거:/);
for(const f of ['preorder.html','glb-electric.html'])assert.match(fs.readFileSync(path.join(root,f),'utf8'),/data-glb-details/);
console.log('Preorder checks passed: four categories; S-Class removed from reservations; EV submodel selector and dedicated pages present.');
